package com.associago.backup;

import org.springframework.stereotype.Service;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.UUID;
import javax.sql.DataSource;
import org.springframework.beans.factory.annotation.Value;

@Service
public class BackupService {

    private final DataSource dataSource;
    private final Path backupDirectory;

    public BackupService(DataSource dataSource, @Value("${associago.data.path}") String dataPath) {
        this.dataSource = dataSource;
        this.backupDirectory = Path.of(dataPath).resolve("backups");
    }

    /** Creates a consistent snapshot of the active SQLite database, including WAL data. */
    public String createBackup() throws IOException {
        Path backup = null;
        try (Connection connection = dataSource.getConnection()) {
            if (!connection.getMetaData().getURL().startsWith("jdbc:sqlite:")) {
                throw new IllegalStateException(
                        "Il backup del database remoto va eseguito dal servizio database. "
                                + "Questa funzione crea solo backup SQLite locali.");
            }
            Files.createDirectories(backupDirectory);
            backup = backupDirectory.resolve("associago_backup_" + UUID.randomUUID() + ".db");
            // The destination is generated by the server. VACUUM INTO includes committed WAL pages;
            // copying the .db file alone can silently omit the latest changes.
            String destination = backup.toAbsolutePath().toString().replace("'", "''");
            try (Statement statement = connection.createStatement()) {
                statement.execute("VACUUM INTO '" + destination + "'");
            }
            return backup.toAbsolutePath().toString();
        } catch (SQLException e) {
            if (backup != null) Files.deleteIfExists(backup);
            throw new IOException("Impossibile creare il backup SQLite.", e);
        }
    }
}
